    // POST /messages — send a direct (to_user_id) or group (group_id) message.
    router.post('/messages', async (req, res) => {
        let conn;
        try {
            const me = await callerChatUser(req);
            const { to_user_id, group_id, body, ticket_id, ticket_number,
                    attachment_id, attachment_name, attachment_mime,
                    sender_public_key, keys } = req.body || {};
            if (!me || (!to_user_id && !group_id) || !body) {
                return res.status(400).json({ error: 'body and one of to_user_id / group_id are required.' });
            }
            // v4: a direct message must carry the wrapped body key for every device
            // that is meant to read it. Without this the message would be
            // undecryptable for everyone, so reject it rather than store garbage.
            if (to_user_id && !group_id) {
                if (!sender_public_key || !Array.isArray(keys) || keys.length === 0) {
                    return res.status(400).json({ error: 'sender_public_key and keys are required for direct messages.' });
                }
            }

            // Rate limit per sender.
            const now = Date.now();
            const counter = sendCounters.get(me.id);
            if (!counter || now - counter.windowStart > SEND_WINDOW_MS) {
                sendCounters.set(me.id, { count: 1, windowStart: now });
            } else {
                counter.count += 1;
                if (counter.count > SEND_LIMIT) return res.status(429).json({ error: 'Rate limit exceeded.' });
            }

            conn = await pool.getConnection();

            // An attachment must exist and belong to the caller's instance.
            let attachmentId = null;
            if (attachment_id) {
                attachmentId = parseInt(attachment_id, 10);
                const arows = await conn.query('SELECT instance_url FROM chat_attachments WHERE id = ?', [attachmentId]);
                if (!arows[0] || arows[0].instance_url !== me.instance_url) {
                    return res.status(400).json({ error: 'Invalid attachment.' });
                }
            }

            let recipient = null;
            let group = null;
            if (group_id) {
                const groupId = parseInt(group_id, 10);
                const grows = await conn.query('SELECT * FROM chat_groups WHERE id = ?', [groupId]);
                group = grows[0];
                if (!group || group.instance_url !== me.instance_url || !(await isGroupMember(conn, groupId, me.id))) {
                    return res.status(403).json({ error: 'Not a member of this group.' });
                }
            } else {
                const rrows = await conn.query('SELECT * FROM chat_users WHERE id = ?', [to_user_id]);
                recipient = rrows[0];
                if (!recipient || recipient.instance_url !== me.instance_url) {
                    return res.status(400).json({ error: 'Invalid recipient.' });
                }
            }

            // For a direct message, only accept envelopes addressed to a device of
            // the recipient or of the sender — nobody else may be handed a key.
            let envelopes = [];
            if (!group) {
                const allowed = await devicesOfUsers(conn, [recipient.id, me.id]);
                const allowedIds = new Set(allowed.map((d) => Number(d.id)));
                for (const entry of keys) {
                    const deviceId = parseInt(entry?.device_id, 10);
                    if (!allowedIds.has(deviceId)) continue;
                    if (typeof entry.wrapped_key !== 'string') continue;
                    envelopes.push([deviceId, entry.wrapped_key]);
                }
                if (!envelopes.length) {
                    return res.status(400).json({ error: 'keys must cover at least one device of the recipient.' });
                }
            }

            const info = await conn.query(`
                INSERT INTO chat_messages
                    (from_user_id, to_user_id, group_id, body, ticket_id, ticket_number,
                     attachment_id, attachment_name, attachment_mime, sender_public_key)
                VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
            `, [
                me.id,
                group ? null : recipient.id,
                group ? group.id : null,
                body,
                ticket_id || null,
                ticket_number || null,
                attachmentId,
                attachmentId ? (attachment_name || null) : null,
                attachmentId ? (attachment_mime || null) : null,
                group ? null : String(sender_public_key),
            ]);
            const insertedId = Number(info.insertId);
            for (const [deviceId, wrappedKey] of envelopes) {
                await conn.query(
                    'INSERT INTO chat_message_keys (message_id, device_id, wrapped_key) VALUES (?, ?, ?)',
                    [insertedId, deviceId, wrappedKey]
                );
            }
            const mrows = await conn.query(`${MESSAGE_SELECT} WHERE m.id = ?`, [me.deviceRowId, insertedId]);
            const message = mrows[0];

            // Best-effort push via the existing APNs pipeline. Never put the
            // message body in the push — it's E2E-encrypted ciphertext. The body
            // is sent as an APNS loc-key so the app localizes it on-device;
            // `body` is only a fallback for clients missing the key.
            if (group) {
                const members = await conn.query(
                    'SELECT user_id FROM chat_group_members WHERE group_id = ? AND user_id <> ?',
                    [group.id, me.id]
                );
                const payload = { chat_group_id: Number(group.id) };
                if (ticket_id) payload.ticketID = ticket_id;
                const push = {
                    title: `${me.name} @ ${group.name}`,
                    bodyLocKey: 'chat_new_message',
                    body: 'New message',
                    payload,
                };
                // Fire and forget — the sender shouldn't wait on APNs.
                pushToUsers(conn, members.map((m) => m.user_id), push, me.deviceRowId).catch(() => {});
            } else {
                const payload = { chat_from_user_id: Number(me.id) };
                if (ticket_id) payload.ticketID = ticket_id;
                // Every device of the recipient. The sender's own other devices are
                // deliberately not pushed — they pick the message up on their next
                // refresh, and "new message" from yourself reads as a bug.
                pushToUsers(conn, [recipient.id], {
                    title: me.name,
                    bodyLocKey: 'chat_new_message',
                    body: 'New message',
                    payload,
                }, me.deviceRowId).catch(() => {});
            }

            res.json(toMessageJson(message));
        } catch (err) {
            console.error('[Chat] send error:', err);
            res.status(500).json({ error: 'Database error.' });
        } finally {
            if (conn) conn.release();
        }
    });

    // POST /read — mark a direct conversation (with_user_id) or a group
