    // POST /groups/:id/keys — hand a group key to member devices that don't have
    // it yet. Callable by any member (they can only pass on a key they could
    // already open), and only ever adds envelopes: an existing one is never
    // overwritten, so a member cannot swap the key out from under the group.
    router.post('/groups/:id/keys', async (req, res) => {
        let conn;
        try {
            const me = await callerChatUser(req);
            if (!me) return res.status(400).json({ error: 'Not registered for chat.' });
            const groupId = parseInt(req.params.id, 10);
            const { wrapped_keys } = req.body || {};
            if (!groupId || !Array.isArray(wrapped_keys) || !wrapped_keys.length) {
                return res.status(400).json({ error: 'wrapped_keys are required.' });
            }

            conn = await pool.getConnection();
            if (!(await isGroupMember(conn, groupId, me.id))) {
                return res.status(403).json({ error: 'Not a member of this group.' });
            }

            // Only devices belonging to members of this group may be given a key.
            const memberRows = await conn.query('SELECT user_id FROM chat_group_members WHERE group_id = ?', [groupId]);
            const memberDevices = await devicesOfUsers(conn, memberRows.map((m) => m.user_id));
            const allowed = new Set(memberDevices.map((d) => Number(d.id)));

            let added = 0;
            for (const entry of wrapped_keys) {
                const deviceId = parseInt(entry?.device_id, 10);
                if (!allowed.has(deviceId)) continue;
                if (typeof entry.wrapped_key !== 'string' || typeof entry.wrapper_public_key !== 'string') continue;
                const result = await conn.query(
                    `INSERT INTO chat_group_device_keys (group_id, device_id, wrapped_key, wrapper_public_key)
                     VALUES (?, ?, ?, ?)
                     ON DUPLICATE KEY UPDATE group_id = group_id`,
                    [groupId, deviceId, entry.wrapped_key, entry.wrapper_public_key]
                );
                if (Number(result.affectedRows) === 1) added += 1;
            }
            res.json({ added });
        } catch (err) {
            console.error('[Chat] group key top-up error:', err);
            res.status(500).json({ error: 'Database error.' });
        } finally {
            if (conn) conn.release();
        }
    });

    // GET /messages?with=13&since=341 — direct messages, ascending.
