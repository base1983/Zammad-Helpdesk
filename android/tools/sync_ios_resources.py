#!/usr/bin/env python3
"""Regenerates Android resources from the iOS sources of truth.

  strings : Zammad Helpdesk/{en,nl,de,fr}.lproj/Localizable.strings
            -> app/src/main/res/values[-xx]/strings.xml  (name = iOS key)
  images  : Assets.xcassets wallpapers/logo -> app/src/main/res/drawable-nodpi
            (downscaled with `sips`, macOS only; pass --images to run)

Run from anywhere:  python3 android/tools/sync_ios_resources.py [--images]
"""
import os, re, subprocess, sys
from xml.sax.saxutils import escape

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
IOS = os.path.join(ROOT, "Zammad Helpdesk")
RES = os.path.join(ROOT, "android", "app", "src", "main", "res")
LANGS = {"en": "values", "nl": "values-nl", "de": "values-de", "fr": "values-fr"}
PAIR = re.compile(r'^\s*"((?:[^"\\]|\\.)*)"\s*=\s*"((?:[^"\\]|\\.)*)"\s*;', re.M)
RESERVED = {"on", "in", "is", "do", "if", "as", "for", "new", "try", "int", "void", "null",
            "true", "false", "class", "this", "super", "import", "package", "return",
            "default", "switch", "case", "break", "continue", "else", "while", "public",
            "private", "static", "final", "long", "short", "byte", "char", "float", "double"}


def res_name(key):
    name = re.sub(r"[^a-z0-9_]", "_", key.lower())
    if name in RESERVED or not re.match(r"[a-z]", name):
        name = "s_" + name
    return name


def unescape_ios(v):
    return (v.replace('\\"', '"').replace("\\n", "\n").replace("\\t", "\t")
             .replace("\\\\", "\\"))


# Platform names that appear inside otherwise shared texts. Strings that are
# wholly iOS-specific (Safari, Apple ID, Face ID) have Android twins in
# strings_android.xml instead and are simply not used by the Android code.
PLATFORM_WORDS = [("Apple Watch", "smartwatch"), ("iOS App Notifications", "Android App Notifications")]


def to_android(v, lang="en"):
    v = unescape_ios(v)
    for ios_word, android_word in PLATFORM_WORDS:
        # German capitalises nouns.
        v = v.replace(ios_word, android_word.capitalize() if lang == "de" and android_word.islower() else android_word)
    # Format specifiers: %@ -> %s, %1$@ -> %1$s. Number them when several occur.
    specs = re.findall(r"%(?:\d+\$)?[@dsf]|%l?[du]|%\.\d+f", v)
    if len(specs) > 1 and not any("$" in s for s in specs):
        counter = [0]
        def repl(m):
            counter[0] += 1
            return "%" + str(counter[0]) + "$" + m.group(1).replace("@", "s").replace("ld", "d")
        v = re.sub(r"%(@|ld|d|s|\.\d+f|f)", repl, v)
    else:
        v = re.sub(r"%(\d+\$)?@", lambda m: "%" + (m.group(1) or "") + "s", v)
        v = v.replace("%ld", "%d")
    has_format = bool(specs)
    if not has_format:
        v = v.replace("%", "%")  # literal percent is fine when formatted="false"
    v = escape(v)
    v = v.replace("\\", "\\\\").replace("'", "\\'").replace('"', '\\"').replace("\n", "\\n")
    v = v.replace("@", "\\@") if v.startswith("@") else v
    v = v.replace("?", "\\?") if v.startswith("?") else v
    return v, has_format


def sync_strings():
    keys_en = None
    for lang, folder in LANGS.items():
        with open(os.path.join(IOS, f"{lang}.lproj", "Localizable.strings"), encoding="utf-8") as f:
            text = f.read()
        text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
        seen, lines = {}, []
        for key, value in PAIR.findall(text):
            name = res_name(key)
            seen[name] = to_android(value, lang)
        if keys_en is None:
            keys_en = set(seen)
        for name in sorted(seen):
            value, has_format = seen[name]
            attr = "" if has_format or "%" not in value else ' formatted="false"'
            lines.append(f'    <string name="{name}"{attr}>{value}</string>')
        os.makedirs(os.path.join(RES, folder), exist_ok=True)
        with open(os.path.join(RES, folder, "strings.xml"), "w", encoding="utf-8") as f:
            f.write('<?xml version="1.0" encoding="utf-8"?>\n'
                    "<!-- GENERATED by android/tools/sync_ios_resources.py from the iOS\n"
                    "     Localizable.strings. Do not edit; Android-only strings live in\n"
                    "     strings_android.xml. -->\n<resources>\n" + "\n".join(lines) + "\n</resources>\n")
        extra = set(seen) - keys_en
        missing = keys_en - set(seen)
        print(f"{lang}: {len(seen)} strings" + (f", missing vs en: {sorted(missing)}" if missing else "")
              + (f", extra: {sorted(extra)}" if extra else ""))


def snake(name):
    return re.sub(r"(?<=[a-z0-9])(?=[A-Z])", "_", name).lower()


def sync_images():
    out = os.path.join(RES, "drawable-nodpi")
    os.makedirs(out, exist_ok=True)
    assets = os.path.join(IOS, "Assets.xcassets")
    for entry in sorted(os.listdir(assets)):
        if not entry.endswith(".imageset"):
            continue
        base = entry[:-9]
        if not (base.startswith("Wallpaper") or base in ("AppBackground", "AppBackgroundThumb", "SplashLogo")):
            continue
        files = [f for f in os.listdir(os.path.join(assets, entry)) if f.lower().endswith((".jpg", ".jpeg", ".png"))]
        if not files:
            continue
        src = os.path.join(assets, entry, sorted(files)[0])
        is_png = base == "SplashLogo"
        dst = os.path.join(out, snake(base) + (".png" if is_png else ".jpg"))
        size = "512" if is_png else ("360" if base.endswith("Thumb") else "2160")
        cmd = ["sips", "-Z", size, src, "--out", dst]
        if not is_png:
            cmd[1:1] = ["-s", "format", "jpeg", "-s", "formatOptions", "72"]
        subprocess.run(cmd, check=True, stdout=subprocess.DEVNULL)
        print(f"{base} -> {os.path.basename(dst)} ({os.path.getsize(dst) // 1024} kB)")


if __name__ == "__main__":
    sync_strings()
    if "--images" in sys.argv:
        sync_images()
